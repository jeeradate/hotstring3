"""Parsing and execution of HotString3 Commands.

A Command is plain text whose first character defines its type:

* ``t<text>``      -- type ``<text>`` into the focused application
* ``s<script>``    -- run ``<script>`` with PowerShell in the background
* ``a<action>``    -- run an internal HotString3 action (``aopen`` opens the UI)
* ``r<script>``    -- run ``<script>`` with PowerShell when HotString3 starts

One optional separator (a space or a colon) directly after the prefix is ignored.
"""

from __future__ import annotations

import ctypes
import logging
import os
import subprocess
import sys
import threading
import time
from contextlib import contextmanager
from dataclasses import dataclass
from typing import Callable, Iterable, Iterator, Literal

from . import config
from .powershell import get_powershell_info

log = logging.getLogger(__name__)

CommandKind = Literal["type", "powershell", "action", "startup"]

#: Windows process creation flag that prevents a console window from flashing up.
CREATE_NO_WINDOW = 0x08000000

POWERSHELL_EXE = "powershell.exe"


# ---------------------------------------------------------------------------
# Command parsing
# ---------------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class ParsedCommand:
    """A validated Command split into its kind and payload."""

    kind: CommandKind
    payload: str
    raw: str


def parse_command(command: str) -> ParsedCommand:
    """Parse and validate a Command string.

    Args:
        command: The raw command, for example ``tHello`` or ``s:Start-Process notepad``.

    Returns:
        The parsed command.

    Raises:
        ValueError: If the command is empty, starts with an unknown prefix or has
            no body (for example ``s`` on its own).
    """
    if not isinstance(command, str):
        raise ValueError("Command must be text.")
    text = command.strip()
    if not text:
        raise ValueError("Command cannot be empty.")

    prefix = text[0]
    kind = config.COMMAND_PREFIXES.get(prefix)
    if kind is None:
        raise ValueError(
            "Command must start with a valid prefix: 't' (type text), "
            "'s' (PowerShell), 'a' (app action) or 'r' (run at startup)."
        )

    payload = text[1:]
    if payload[:1] in (" ", ":"):
        payload = payload[1:]

    if not payload:
        raise ValueError(f"The command after '{prefix}' cannot be empty.")

    return ParsedCommand(kind=kind, payload=payload, raw=command)  # type: ignore[arg-type]


def validate_command(command: str) -> ParsedCommand:
    """Validate a Command and return its parsed form (alias of :func:`parse_command`)."""
    return parse_command(command)


def powershell_argv(script: str, executable: str = POWERSHELL_EXE) -> list[str]:
    """Build the argv used to run ``script`` in a hidden PowerShell process.

    Args:
        script: The PowerShell script to run.
        executable: PowerShell executable to launch.  Defaults to
            ``powershell.exe``; the executor passes the detected one.
    """
    return [
        executable,
        "-NoProfile",
        "-WindowStyle",
        "Hidden",
        "-ExecutionPolicy",
        "Bypass",
        "-Command",
        script,
    ]


# ---------------------------------------------------------------------------
# Input suppression
# ---------------------------------------------------------------------------

_suppression_depth = 0
_suppression_lock = threading.Lock()


def is_input_suppressed() -> bool:
    """Return ``True`` while HotString3 itself is sending keystrokes."""
    with _suppression_lock:
        return _suppression_depth > 0


@contextmanager
def suppress_input() -> Iterator[None]:
    """Ignore keyboard events generated by HotString3 itself (re-entrance guard)."""
    global _suppression_depth
    with _suppression_lock:
        _suppression_depth += 1
    try:
        yield
    finally:
        with _suppression_lock:
            _suppression_depth = max(0, _suppression_depth - 1)


# ---------------------------------------------------------------------------
# Typing (clipboard based, Unicode and multi-line safe)
# ---------------------------------------------------------------------------

CF_UNICODETEXT = 13
GMEM_MOVEABLE = 0x0002

if sys.platform == "win32":
    import ctypes.wintypes as wintypes

    _user32 = ctypes.windll.user32
    _kernel32 = ctypes.windll.kernel32

    _user32.OpenClipboard.argtypes = [wintypes.HWND]
    _user32.OpenClipboard.restype = wintypes.BOOL
    _user32.CloseClipboard.restype = wintypes.BOOL
    _user32.GetClipboardData.argtypes = [wintypes.UINT]
    _user32.GetClipboardData.restype = wintypes.HANDLE
    _user32.SetClipboardData.argtypes = [wintypes.UINT, wintypes.HANDLE]
    _user32.SetClipboardData.restype = wintypes.HANDLE
    _user32.EmptyClipboard.restype = wintypes.BOOL
    _kernel32.GlobalAlloc.argtypes = [wintypes.UINT, ctypes.c_size_t]
    _kernel32.GlobalAlloc.restype = wintypes.HGLOBAL
    _kernel32.GlobalLock.argtypes = [wintypes.HGLOBAL]
    _kernel32.GlobalLock.restype = ctypes.c_void_p
    _kernel32.GlobalUnlock.argtypes = [wintypes.HGLOBAL]
    _kernel32.GlobalUnlock.restype = wintypes.BOOL
else:  # pragma: no cover - HotString3 targets Windows, this only aids development
    _user32 = None
    _kernel32 = None


def _open_clipboard(retries: int = 10) -> None:
    assert _user32 is not None
    for _ in range(retries):
        if _user32.OpenClipboard(None):
            return
        time.sleep(0.02)
    raise RuntimeError("Could not open the Windows clipboard.")


def get_clipboard_text() -> str | None:
    """Return the current clipboard text, or ``None`` if it holds no text."""
    if sys.platform != "win32" or _user32 is None or _kernel32 is None:
        return None

    _open_clipboard()
    try:
        handle = _user32.GetClipboardData(CF_UNICODETEXT)
        if not handle:
            return None
        pointer = _kernel32.GlobalLock(handle)
        if not pointer:
            return None
        try:
            return ctypes.wstring_at(pointer)
        finally:
            _kernel32.GlobalUnlock(handle)
    finally:
        _user32.CloseClipboard()


def set_clipboard_text(text: str) -> None:
    """Put ``text`` (Unicode, multi-line) on the Windows clipboard."""
    if sys.platform != "win32" or _user32 is None or _kernel32 is None:
        raise RuntimeError("Clipboard access is only supported on Windows.")

    data = text.encode("utf-16-le") + b"\x00\x00"
    handle = _kernel32.GlobalAlloc(GMEM_MOVEABLE, len(data))
    if not handle:
        raise RuntimeError("Could not allocate clipboard memory.")

    pointer = _kernel32.GlobalLock(handle)
    if not pointer:
        raise RuntimeError("Could not lock clipboard memory.")
    try:
        ctypes.memmove(pointer, data, len(data))
    finally:
        _kernel32.GlobalUnlock(handle)

    _open_clipboard()
    try:
        _user32.EmptyClipboard()
        if not _user32.SetClipboardData(CF_UNICODETEXT, handle):
            raise RuntimeError("Could not write to the Windows clipboard.")
    finally:
        _user32.CloseClipboard()


def _keyboard_controller():
    from pynput.keyboard import Controller  # imported lazily so tests need no input device

    return Controller()


def type_text(text: str) -> None:
    """Paste ``text`` into the focused application using the clipboard.

    A simulated paste (``Ctrl+V``) is used instead of per-character keystrokes
    because it reliably supports Unicode (including Thai) and multi-line text
    and is independent of the active keyboard layout.  The previous clipboard
    text is restored afterwards.
    """
    if not text:
        return

    from pynput.keyboard import Key

    previous = get_clipboard_text()
    set_clipboard_text(text)
    time.sleep(0.03)

    controller = _keyboard_controller()
    with suppress_input():
        controller.press(Key.ctrl)
        try:
            controller.press("v")
            controller.release("v")
        finally:
            controller.release(Key.ctrl)
        time.sleep(0.2)

    if previous is not None:
        try:
            set_clipboard_text(previous)
        except RuntimeError as exc:  # restoring is best effort
            log.warning("Could not restore the clipboard: %s", exc)


def send_backspaces(count: int, delay: float = 0.008) -> None:
    """Send ``count`` Backspace keystrokes, without feeding them back into the buffer."""
    if count <= 0:
        return

    from pynput.keyboard import Key

    controller = _keyboard_controller()
    with suppress_input():
        for _ in range(count):
            controller.press(Key.backspace)
            controller.release(Key.backspace)
            time.sleep(delay)
        time.sleep(0.02)


# ---------------------------------------------------------------------------
# Execution
# ---------------------------------------------------------------------------


class CommandExecutor:
    """Execute parsed Commands.

    The heavy lifting is delegated to injectable handlers so that the class can
    be unit tested without a real keyboard, clipboard or PowerShell process.

    Args:
        open_ui: Callback invoked for the ``aopen`` internal action.
        on_error: Callback invoked with a human readable error message.  Used for
            tray notifications; errors are always logged as well.
        typing_handler: Replacement for :func:`type_text`.
        powershell_handler: Replacement for :meth:`run_powershell`.
    """

    def __init__(
        self,
        *,
        open_ui: Callable[[], None] | None = None,
        on_error: Callable[[str], None] | None = None,
        typing_handler: Callable[[str], None] | None = None,
        powershell_handler: Callable[[str], None] | None = None,
    ) -> None:
        self._open_ui = open_ui
        self._on_error = on_error
        self._typing_handler = typing_handler or type_text
        self._powershell_handler = powershell_handler or self.run_powershell

    # -- public API ---------------------------------------------------------
    def execute(self, command: str) -> bool:
        """Execute ``command`` in the calling thread.

        Returns:
            ``True`` if the command was handled, ``False`` if it was invalid or
            failed.  Exceptions are never raised: the listener must stay alive.
        """
        try:
            parsed = parse_command(command)
        except ValueError as exc:
            self._report_error(str(exc))
            return False

        try:
            if parsed.kind == "type":
                self._typing_handler(parsed.payload)
            elif parsed.kind in ("powershell", "startup"):
                self._powershell_handler(parsed.payload)
            else:
                self._run_action(parsed.payload)
        except Exception as exc:  # noqa: BLE001 - one bad command must not kill the app
            log.exception("Command failed: %r", command)
            self._report_error(f"Command failed: {exc}")
            return False
        return True

    def execute_async(self, command: str) -> threading.Thread:
        """Execute ``command`` on a worker thread so the keyboard hook never blocks."""

        def target() -> None:
            self.execute(command)

        thread = threading.Thread(target=target, name="hotstring3-command", daemon=True)
        thread.start()
        return thread

    def run_startup_commands(self, commands: Iterable[str]) -> None:
        """Run every ``r`` command on a worker thread at application start."""
        for command in commands:
            try:
                parsed = parse_command(command)
            except ValueError as exc:
                log.warning("Skipping invalid startup command %r: %s", command, exc)
                continue
            if parsed.kind != "startup":
                continue
            log.info("Running startup command: %s", parsed.payload)
            self._powershell_handler(parsed.payload)

    # -- internals ----------------------------------------------------------
    def _run_action(self, action: str) -> None:
        if action == "open":
            if self._open_ui is None:
                raise RuntimeError("No UI handler is configured.")
            self._open_ui()
        else:
            raise ValueError(f"Unknown internal action '{action}'.")

    def _report_error(self, message: str) -> None:
        log.error(message)
        if self._on_error is not None:
            try:
                self._on_error(message)
            except Exception:  # noqa: BLE001
                log.exception("Error callback failed")

    def run_powershell(self, script: str) -> None:
        """Start ``script`` in a hidden PowerShell process and log its output.

        The process is launched with ``CREATE_NO_WINDOW`` and its output is
        collected on a background thread, so the caller returns immediately.
        """
        info = get_powershell_info()
        log.info("Running PowerShell (%s): %s", info.status_text(), script)
        try:
            process = subprocess.Popen(  # noqa: S603 - scripts come from the user's own HotStrings
                powershell_argv(script, info.executable),
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
                text=True,
                encoding="utf-8",
                errors="replace",
                creationflags=CREATE_NO_WINDOW if sys.platform == "win32" else 0,
            )
        except OSError as exc:
            log.error("Could not start PowerShell: %s", exc)
            self._report_error(f"Could not start PowerShell: {exc}")
            return

        def collect() -> None:
            stdout, stderr = process.communicate()
            if stdout.strip():
                log.info("PowerShell stdout: %s", stdout.strip())
            if stderr.strip():
                log.warning("PowerShell stderr: %s", stderr.strip())
            log.info("PowerShell exited with code %s", process.returncode)
            if process.returncode not in (0, None):
                self._report_error(
                    f"PowerShell exited with code {process.returncode}. See the log for details."
                )

        threading.Thread(target=collect, name="hotstring3-powershell", daemon=True).start()
